"""Import a reviewed selection as immutable photos; never overwrite app fallbacks.

Usage: python3 scripts/prepare-photo-library.py /absolute/path/to/image-audit-folder
Produces the versioned static files, a CMS manifest and an idempotent D1 import.
The original PNG masters remain in the review folder; existing WebP files are
copied byte-for-byte into the archive before a new version is prepared.
"""
import hashlib
import json
import sys
from pathlib import Path
from PIL import Image, ImageOps

root = Path(__file__).resolve().parent.parent
review = Path(sys.argv[1]).resolve()
selected = json.loads((review / 'selected-photos.json').read_text())
files = root / 'public/media/photos'
files.mkdir(parents=True, exist_ok=True)
versions = []
active = {}
source_imports = []
source_pairs = []
titles = {}
timestamp = 1793347200000  # 30 October 2026, stable import identifier

def archive(data):
    digest = hashlib.sha256(data).hexdigest()
    (files / (digest + '.webp')).write_bytes(data)
    return '/media/photos/' + digest + '.webp'

def image_bytes(path, width):
    import io
    with Image.open(path) as image:
        image = ImageOps.exif_transpose(image).convert('RGB')
        if image.width > width:
            image = image.resize((width, round(image.height * width / image.width)), Image.Resampling.LANCZOS)
        output = io.BytesIO()
        image.save(output, 'WEBP', quality=80, method=6)
        return output.getvalue(), image.size

for index, item in enumerate(sorted(selected, key=lambda r: r['n'])):
    slot = str(Path(item['targets'][0]).with_suffix('.webp'))
    titles[slot] = item['name']
    old = root / 'src/assets' / slot
    old_small = old.with_name(old.stem + '-640.webp')
    with Image.open(old) as image:
        width, height = image.size
    with Image.open(old_small) as image:
        small_width = image.width
    data = old.read_bytes()
    old_src = archive(data)
    old_id = hashlib.sha256((slot + old_src).encode()).hexdigest()
    versions.append(dict(id=old_id, slot=slot, label='Precedente', src=old_src,
        smallSrc=archive(old_small.read_bytes()), width=width, height=height,
        smallWidth=small_width, createdAt=timestamp - 86400000))
    master = review / item['image']
    if item['n'] == 9:
        master = review / 'round8/pinsa.png'
    elif item['n'] == 26:
        master = review / 'round8/almetro.png'
    new_data, (width, height) = image_bytes(master, 1280)
    small_data, (small_width, _) = image_bytes(master, 640)
    new_src = archive(new_data)
    new_id = hashlib.sha256((slot + new_src).encode()).hexdigest()
    versions.append(dict(id=new_id, slot=slot, label='Scelta · 30 ottobre 2026',
        src=new_src, smallSrc=archive(small_data), width=width, height=height,
        smallWidth=small_width, createdAt=timestamp))
    active[slot] = new_id
    source_imports.append(f'import photo{index} from "../../assets/{slot}";')
    source_pairs.append(f'  [photo{index}, {json.dumps(slot)}],')

(root / 'src/app/data/media-source-map.ts').write_text(
    '// Generated by scripts/prepare-photo-library.py. Stable CMS slots for bundled fallbacks.\n'
    + '\n'.join(source_imports) + '\nexport const MEDIA_SOURCE_SLOTS = new Map<string, string>([\n'
    + '\n'.join(source_pairs) + '\n]);\n')
manifest = dict(versions=versions, active=active, titles=titles)
(root / 'public/media/catalog.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n')
def quote(value):
    return "'" + str(value).replace("'", "''") + "'"
sql = (root / 'migrations/0001-photo-library.sql').read_text() + '\n'
for version in versions:
    values = [version[k] for k in ['id', 'slot', 'label', 'src', 'smallSrc', 'width', 'height', 'smallWidth', 'createdAt']]
    sql += 'INSERT OR IGNORE INTO media_versions (id,slot,label,src,small_src,width,height,small_width,created_at) VALUES (' + ','.join(quote(v) for v in values) + ');\n'
for slot, version in active.items():
    sql += 'INSERT OR IGNORE INTO media_publications (slot,version_id,updated_at) VALUES (' + ','.join(quote(v) for v in [slot, version, timestamp]) + ');\n'
(root / 'migrations/0002-reviewed-photos.sql').write_text(sql)
print(f'{len(active)} CMS slots; {len(versions)} versions with originals preserved; {len(list(files.glob("*.webp")))} responsive files.')
